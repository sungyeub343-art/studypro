def dong_base(name: str) -> str:
    # 범어1동·수성2·3가동 → 범어동·수성동, 수성동1가·칠성동2가 → 수성동·칠성동
    name = re.sub(r"\d+가$", "", name)
    return re.sub(r"[\d·]+가?(?=동$)", "", name)


